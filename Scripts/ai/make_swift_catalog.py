#!/usr/bin/env python3
"""Generates Sources/PhotoFlow/AI/AIModelCatalogData.swift (embedded JSON) from
   - catalog/files.json        (Hugging Face files pinned to a revision, with size + SHA-256)
   - manifest.json             (Real-ESRGAN Core ML packages in release ai-models-v1)
   - lama-manifest.json        (LaMa Core ML package in release ai-models-v1)
Release assets are re-hashed from local copies (argument 4: folder with the downloaded release assets),
so the app's expected checksums are exactly those of the hosted files.
Usage: make_swift_catalog.py files.json manifest.json lama-manifest.json release-folder out.swift"""
import hashlib, json, os, sys

files_json, esrgan_json, lama_json, release_dir, out = sys.argv[1:6]


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


catalog = {}
for mid, e in json.load(open(files_json)).items():
    catalog[mid] = {"revision": e["revision"],
                    "files": [{"path": f["path"], "url": f["url"], "size": f["size"], "sha256": f["sha256"]} for f in e["files"]]}

manifests = json.load(open(esrgan_json))
manifests.update(json.load(open(lama_json)))
for mid, m in manifests.items():
    local = os.path.join(release_dir, m["file"])
    size, digest = os.path.getsize(local), sha(local)
    assert size == m["size"] and digest == m["sha256"], f"{mid}: release asset differs from manifest"
    catalog[mid] = {"revision": "ai-models-v1 · weights " + (m.get("weights_sha256") or "")[:12],
                    "files": [{"path": m["file"], "url": "https://github.com/jpimmobilien/photoflow-mac/releases/download/ai-models-v1/" + m["file"],
                               "size": size, "sha256": digest}]}

payload = json.dumps(catalog, separators=(",", ":"), sort_keys=True)
assert '"""' not in payload
with open(out, "w") as f:
    f.write("// Generated by Scripts/ai/make_swift_catalog.py – do not edit.\n")
    f.write("// Pinned download list (URL, size, SHA-256) for every model in AIModelCatalog.\n\n")
    f.write("enum AIModelCatalogData {\n    static let json = #\"\"\"\n")
    f.write(payload)
    f.write("\n\"\"\"#\n}\n")
print("models:", ", ".join(f"{k} ({sum(x['size'] for x in v['files'])/1e6:.0f} MB)" for k, v in catalog.items()))
